"""Reconcile the four-layer 138-pair manuscript claims.

This is an analysis-only tool. It does not run model inference or modify
source/data artifacts. It compares staged reproduction outputs, archived
audit summaries, manuscript targets, and provenance hashes.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
STAGE = ROOT / "repro_candidate_138"
RAG = Path(r"D:\FPT\Semester_8\RAG_Research")
OUT = ROOT / "reports" / "reconciliation_138"

TARGETS = {
    "SW-BTED": 0.9498,
    "B1: Cosine TF-IDF": 0.4364,
    "B2: Full-document SBERT": 0.9867,
    "B3: Standard TED": 0.4364,
    "B4: pq-Gram": 0.9479,
    "B5: Section Cosine": 0.4081,
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_csv(path: Path):
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def f(value):
    return float(value)


def markdown_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out.extend("| " + " | ".join(str(row.get(h, "")) for h in headers) + " |" for row in rows)
    return "\n".join(out)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    staged_metrics = read_csv(STAGE / "results" / "evaluation_metrics.csv")
    audit_rows = read_csv(RAG / "results" / "audit" / "real_vs_augmented_breakdown.csv")
    staged_pairs = read_csv(STAGE / "results" / "pair_similarities.csv")
    staged_pairs_input = read_csv(STAGE / "data" / "dataset" / "pairs.csv")
    structural_path = STAGE / "results" / "structural_only_metrics.json"
    structural = json.loads(structural_path.read_text(encoding="utf-8")) if structural_path.exists() else None

    metrics = {row["Method"]: row for row in staged_metrics}
    audit = {row["method"]: row for row in audit_rows if row["slice"] == "Real-only"}

    comparison = []
    for method, target in TARGETS.items():
        stage_name = method
        if method == "B2: Full-document SBERT":
            stage_name = "B2: Cosine SBERT"
        row = metrics.get(stage_name)
        audit_row = audit.get(method.replace("Full-document SBERT", "Cosine SBERT"))
        stage_value = f(row["F1_Score_Mean"]) if row else None
        audit_value = f(audit_row["f1_mean"]) if audit_row else None
        comparison.append({
            "Method": method,
            "Manuscript F1": f"{target:.4f}",
            "Staged F1": f"{stage_value:.4f}" if stage_value is not None else "missing",
            "Audit real-only F1": f"{audit_value:.4f}" if audit_value is not None else "missing",
            "Stage delta": f"{stage_value - target:+.4f}" if stage_value is not None else "missing",
            "Audit delta": f"{audit_value - target:+.4f}" if audit_value is not None else "missing",
        })

    provenance_paths = [
        STAGE / "config.yaml",
        STAGE / "data" / "dataset" / "pairs.csv",
        STAGE / "data" / "dataset" / "trees_section.json",
        STAGE / "data" / "dataset" / "full_texts.json",
        STAGE / "src" / "05_sw_bted.py",
        STAGE / "src" / "baselines.py",
        STAGE / "experiments" / "main_evaluation.py",
    ]
    provenance = []
    for path in provenance_paths:
        if path.exists():
            stat = path.stat()
            provenance.append({
                "Path": str(path.relative_to(ROOT)),
                "Bytes": stat.st_size,
                "LastWriteTime": str(__import__("datetime").datetime.fromtimestamp(stat.st_mtime)),
                "SHA256": sha256(path)[:16],
            })

    prediction_columns = [key for key in staged_pairs[0] if key.startswith("pred_")] if staged_pairs else []
    report = f"""# 138-Pair Reconciliation Results

Generated by `experiments/reconcile_138.py`.

This report is analysis-only. No model inference was executed by the
reconciliation script; inference was completed previously in the isolated
`repro_candidate_138` staging directory.

## Dataset integrity

- Staged pair rows: **{len(staged_pairs_input)}**
- Type A: **{sum(row['type'] == 'Type_A' for row in staged_pairs_input)}**
- Type B: **{sum(row['type'] == 'Type_B' for row in staged_pairs_input)}**
- Type C: **{sum(row['type'] == 'Type_C' for row in staged_pairs_input)}**
- Raw prediction rows: **{len(staged_pairs)}**
- Prediction columns: `{', '.join(prediction_columns)}`

## Manuscript versus recovered results

{markdown_table(['Method', 'Manuscript F1', 'Staged F1', 'Audit real-only F1', 'Stage delta', 'Audit delta'], comparison)}

## Interpretation

- SW-BTED is close in both the staged run and the audit slice, but the staged
  run does not exactly reproduce the manuscript value or its reported fold
  variance.
- The baseline rows are not all from one unambiguous implementation/scope:
  their audit values and staged values differ from the manuscript targets.
- The staged harness selected `alpha=0.8` and `beta=per_layer` in all folds,
  so it is a configuration-search/hybrid harness, not a direct fixed
  structural-only reproduction.
- The canonical source set is therefore still unresolved.

## Provenance of the staging run

{markdown_table(['Path', 'Bytes', 'LastWriteTime', 'SHA256'], provenance)}

## Required next reconciliation

1. Recover the raw structural-only score/prediction file that produced the
   manuscript's `0.9498`.
2. Recover the exact full-prose SBERT path producing `0.9867`.
3. Recover the exact pq-Gram and Section Cosine input scopes producing
   `0.9479` and `0.4081`.
4. Compare pair-level predictions before changing any code.

Status: **candidate pipeline executable; manuscript provenance unresolved**.
"""
    (OUT / "RECONCILIATION_REPORT.md").write_text(report, encoding="utf-8")
    (OUT / "provenance_manifest.json").write_text(json.dumps({"comparison": comparison, "provenance": provenance}, indent=2), encoding="utf-8")
    print(OUT / "RECONCILIATION_REPORT.md")


if __name__ == "__main__":
    main()
